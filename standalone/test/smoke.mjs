import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

const temp = await mkdtemp(path.join(tmpdir(), 'standalone-aiocr-'));
process.env.AIOCR_DATA_DIR = temp;
process.env.AIOCR_BACKUP_DIR = path.join(temp, 'backups');
process.env.AIOCR_PORT = '0';
process.env.AIOCR_USERNAME = 'test-admin';
process.env.AIOCR_PASSWORD = 'test-password';
process.env.AIOCR_FACILITY_ID = 'facility-a';
process.env.AIOCR_ENCRYPTION_KEY = 'test-only-encryption-key-32-characters-minimum';
const { server } = await import('../server.mjs');
await new Promise(resolve => server.listening ? resolve() : server.once('listening', resolve));
const address = server.address();
const base = `http://127.0.0.1:${address.port}`;
const auth = `Basic ${Buffer.from('test-admin:test-password').toString('base64')}`;
const health = await fetch(`${base}/api/health`).then(r => r.json());
assert.equal(health.ok, true);
assert.equal(health.imageDetail, 'high');
const captureHtml = await readFile(new URL('../public/index.html', import.meta.url), 'utf8');
assert.match(captureHtml, /id="imageInput"[^>]*accept="image\/\*"[^>]*multiple/);
assert.doesNotMatch(captureHtml, /id="imageInput"[^>]*capture=/);
const captureApp = await readFile(new URL('../public/app.js', import.meta.url), 'utf8');
assert.match(captureApp, /resizeLongEdge\(dataUrl,maxLongEdge=2048\)/);
assert.match(captureApp, /resizeLongEdge\(await cropToOcrContent\(source\)\)/);
assert.match(captureApp, /state\.imageDataUrls=await Promise\.all\(files\.map\(read\)\)/);
assert.match(captureApp, /余白削除・縮小・画像補正を行わず原画像を使用/);
assert.match(captureApp, /const median=channel=>/);
assert.match(captureApp, /const sustainedBounds=/);
assert.match(captureHtml, /id="batchComparisons"/);
assert.match(captureApp, /function renderBatchComparisons\(\)/);
assert.match(captureApp, /OCR結果（テキスト）/);
const denied = await fetch(`${base}/api/patients`);
assert.equal(denied.status, 401);
const loginResponse = await fetch(`${base}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'test-admin', password: 'test-password' }) });
assert.equal(loginResponse.status, 200);
const sessionCookie = loginResponse.headers.get('set-cookie').split(';')[0];
const sessionPatientsResponse = await fetch(`${base}/api/patients`, { headers: { Cookie: sessionCookie } });
assert.equal(sessionPatientsResponse.status, 200);
const patientResponse = await fetch(`${base}/api/patients`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: auth }, body: JSON.stringify({ facilityPatientId: 'P001', name: 'テスト患者', birthDate: '1950-01-01' }) });
assert.equal(patientResponse.status, 201);
const patient = await patientResponse.json();
assert.match(patient.id, /^patient_/);
const patients = await fetch(`${base}/api/patients`, { headers: { Authorization: auth } }).then(r => r.json());
assert.equal(patients.length, 1);
assert.equal(patients[0].name, 'テスト患者');
const tinyPng = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=';
const jobResponse = await fetch(`${base}/api/jobs`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: auth }, body: JSON.stringify({ patientId: patient.id, imageDataUrl: tinyPng }) });
assert.equal(jobResponse.status, 202);
const createdJob = await jobResponse.json();
assert.equal(createdJob.status, 'REQUEST');
assert.equal(createdJob.evaluationType, '帳票判定中');
const parallelJobResponse = await fetch(`${base}/api/jobs`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: auth }, body: JSON.stringify({ patientId: patient.id, imageDataUrl: tinyPng }) });
assert.equal(parallelJobResponse.status, 202);
const parallelJob = await parallelJobResponse.json();
assert.notEqual(parallelJob.id, createdJob.id);
const runningJobs = await fetch(`${base}/api/jobs`, { headers: { Authorization: auth } }).then(r => r.json());
assert.ok(runningJobs.some(job => job.id === createdJob.id));
assert.ok(runningJobs.some(job => job.id === parallelJob.id));
let finishedJob, finishedParallelJob;
for (let attempt = 0; attempt < 30; attempt += 1) {
  await new Promise(resolve => setTimeout(resolve, 25));
  [finishedJob, finishedParallelJob] = await Promise.all([
    fetch(`${base}/api/jobs/${createdJob.id}`, { headers: { Authorization: auth } }).then(r => r.json()),
    fetch(`${base}/api/jobs/${parallelJob.id}`, { headers: { Authorization: auth } }).then(r => r.json())
  ]);
  if (finishedJob.status === 'ERROR' && finishedParallelJob.status === 'ERROR') break;
}
assert.equal(finishedJob.status, 'ERROR');
assert.equal(finishedParallelJob.status, 'ERROR');
assert.match(finishedJob.error, /OPENAI_API_KEY/);
const audit = await fetch(`${base}/api/audit`, { headers: { Authorization: auth } }).then(r => r.json());
assert.ok(audit.some(entry => entry.action === 'OCR_FAILED'));
const clearAuditResponse = await fetch(`${base}/api/audit`, { method: 'DELETE', headers: { Authorization: auth } });
assert.equal(clearAuditResponse.status, 200);
const clearAuditResult = await clearAuditResponse.json();
assert.ok(clearAuditResult.deletedCount > 0);
const clearedAudit = await fetch(`${base}/api/audit`, { headers: { Authorization: auth } }).then(r => r.json());
assert.deepEqual(clearedAudit, []);
const databaseBytes = await readFile(path.join(temp, 'database.json'));
assert.equal(databaseBytes.subarray(0, 6).toString(), 'AIOCR1');
assert.equal(databaseBytes.includes(Buffer.from('テスト患者')), false);
const imageBytes = await readFile(path.join(temp, 'images', createdJob.imageFile));
assert.equal(imageBytes.subarray(0, 6).toString(), 'AIOCR1');
const backupResponse = await fetch(`${base}/api/admin/backup`, { method: 'POST', headers: { Authorization: auth, 'Content-Type': 'application/json' }, body: '{}' });
assert.equal(backupResponse.status, 201);
const backup = await backupResponse.json();
assert.match(backup.backup, /^backup-/);
const backupManifest = JSON.parse(await readFile(path.join(temp, 'backups', backup.backup, 'manifest.json'), 'utf8'));
assert.equal(backupManifest.encrypted, true);
await new Promise(resolve => server.close(resolve));
await rm(temp, { recursive: true, force: true });
console.log('standalone smoke test: OK');
